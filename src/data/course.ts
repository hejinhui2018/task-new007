export function getChapter(id: string | undefined | null): Chapter | null {
  if (!id) return null;
  return course.chapters.find((chapter) => chapter.id === id) ?? null;
}

export function getAdjacentChapters(id: string): { prev: Chapter | null; next: Chapter | null } {
  const index = course.chapters.findIndex((chapter) => chapter.id === id);
  if (index === -1) return { prev: null, next: null };
  return {
    prev: course.chapters[index - 1] ?? null,
    next: course.chapters[index + 1] ?? null,
  };
}
